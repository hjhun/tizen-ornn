#!/usr/bin/env bash
# Install the upstream Tizen Studio native packaging CLI and its SDK dependencies.
set -euo pipefail
project=$(cd "$(dirname "$0")/.." && pwd)
root=${1:?usage: install-sdk.sh STAGED_ROOT}
[[ -d "$root" && "$(realpath "$root")" != / ]] || exit 2
cache=${CACHE_DIR:-$project/out/cache/sdk}
mkdir -p "$cache" "$root/opt/tizen-sdk" "$root/usr/local/bin"
work=$(mktemp -d)
trap 'rm -rf "$work"' EXIT
while read -r hash file; do
    target=$cache/$file
    if [[ ! -f "$target" ]]; then
        curl -fLsS --retry 3 "https://download.tizen.org/sdk/tizenstudio/official/binary/$file" -o "$target.part"
        mv "$target.part" "$target"
    fi
    printf '%s  %s\n' "$hash" "$target" | sha256sum -c -
    unzip -qo "$target" 'data/*' -d "$work"
done < "$project/sdk/packages.sha256"
cp -a "$work/data/." "$root/opt/tizen-sdk/"
# The launcher runs from the caller's private state directory, so the SDK
# resolves its relative data path there and writes no state under /opt.
cat > "$root/opt/tizen-sdk/sdk.info" <<'INFO'
TIZEN_SDK_INSTALLED_PATH=/opt/tizen-sdk
TIZEN_SDK_DATA_PATH=.
INFO
cat > "$root/opt/tizen-sdk/tools/.tizen-cli-config" <<'CONFIG'
#This is generated by Tizen CLI! (1.3)
default.build.architecture=x86_64
default.build.configuration=Debug
default.build.compiler=gcc
default.profiles.path=./profile/profiles.xml
CONFIG
install -m 0755 "$project/sdk/tizen" "$root/usr/local/bin/tizen"
ln -sfn /opt/tizen-sdk/tools/sdb "$root/usr/local/bin/sdb"
sample=$root/usr/share/tizen-dev/examples/native-tpk
mkdir -p "$sample"
for file in .project project_def.prop tizen-manifest.xml tizenprobe.cc; do
    install -m 0644 "$project/sdk/native-example/$file" "$sample/$file"
done
install -m 0755 "$project/sdk/native-example/package.sh" "$sample/package.sh"
